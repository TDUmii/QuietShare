"""Annotate real QuietShare QA captures for clickable visual guides.

Input captures are generated by local UI QA, not synthetic mockups.
Output is documentation artwork. Works offline with Pillow.
Usage: python tools/annotate_visual_guide.py
"""
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "artifacts" / "qa-visible"
OUTPUT = ROOT / "docs" / "images" / "visual"
OUTPUT.mkdir(parents=True, exist_ok=True)
VERSION = re.search(r'^#define QUIETSHARE_VERSION_TEXT "([^"]+)"',
                    (ROOT / "src" / "Version.h").read_text(encoding="utf-8-sig"), re.M).group(1)

# Coordinates are relative to the unscaled v0.21 real UI captures.
CAPTURES = {
    "01-home.png": ("home.bmp", [
        (89, 113, 217, 152), (227, 113, 371, 152), (7, 504, 43, 534)
    ]),
    "02-files.png": ("code-file.bmp", [
        (7, 81, 43, 116), (57, 31, 190, 60), (676, 31, 712, 60)
    ]),
    "03-script.png": ("editing.bmp", [
        (59, 94, 694, 531), (389, 60, 473, 86), (552, 60, 577, 86)
    ]),
    "04-pdf.png": ("pdf-file.bmp", [
        (58, 60, 198, 88), (202, 60, 301, 88), (540, 31, 672, 59)
    ]),
    "05-settings.png": ("settings-appearance.bmp", [
        (58, 80, 216, 114), (610, 188, 791, 222), (662, 268, 791, 302)
    ]),
    "06-browser.png": ("browser-off.bmp", [
        (7, 118, 43, 154), (58, 79, 222, 108), (7, 504, 43, 534)
    ]),
    "07-projection.png": ("presentation.bmp", [
        (108, 79, 816, 144), (149, 147, 325, 176), (278, 273, 596, 453)
    ]),
    "08-recording.png": ("meeting.bmp", [
        (58, 80, 212, 108), (219, 80, 337, 108), (317, 166, 818, 531)
    ]),
}
try:
    FONT = ImageFont.truetype("C:/Windows/Fonts/arialbd.ttf", 18)
    SMALL = ImageFont.truetype("C:/Windows/Fonts/arial.ttf", 13)
except OSError:
    FONT = ImageFont.load_default()
    SMALL = FONT

for name, (original, targets) in CAPTURES.items():
    src = SOURCE / original
    if not src.is_file():
        raise SystemExit(f"Missing real QA screenshot: {src}")
    im = Image.open(src).convert("RGB")
    out = Image.new("RGB", (im.width, im.height + 31), (20, 24, 29))
    out.paste(im, (0, 0))
    draw = ImageDraw.Draw(out)
    for index, (left, top, right, bottom) in enumerate(targets, 1):
        draw.rectangle((left, top, right, bottom), outline=(255, 49, 54), width=4)
        # Put the step marker near the outlined corner, without hiding the target.
        x = min(max(left + 9, 22), im.width - 23)
        y = top - 14 if top >= 27 else top + 12
        y = max(20, min(im.height - 20, y))
        if name == "07-projection.png" and index == 1:
            x, y = 300, 61
        if name == "07-projection.png" and index == 2:
            x, y = 146, 147
        draw.ellipse((x - 17, y - 17, x + 17, y + 17),
                     fill=(228, 24, 34), outline=(255, 255, 255), width=2)
        box = draw.textbbox((0, 0), str(index), font=FONT)
        draw.text((x - (box[2]-box[0])/2, y - (box[3]-box[1])/2 - box[1]),
                  str(index), fill=(255, 255, 255), font=FONT)
    footer = "Viền đỏ = nơi cần nhấn  |  Red outline = click target  |  QuietShare " + VERSION
    draw.text((12, im.height + 8), footer, font=SMALL, fill=(221, 230, 235))
    out = out.resize((out.width * 2, out.height * 2), Image.Resampling.LANCZOS)
    dest = OUTPUT / name
    out.save(dest, optimize=True)
    print(f"{dest.relative_to(ROOT)} : {out.width}x{out.height} : {dest.stat().st_size} bytes")
